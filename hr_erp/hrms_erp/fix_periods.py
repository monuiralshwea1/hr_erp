def execute():
    for shift_name, periods in SHIFT_DEFS.items():
        existing = frappe.db.sql(
            "SELECT COUNT(*) as cnt FROM `tabShift Period` WHERE parent=%s", shift_name, as_dict=True
        )
        if existing and existing[0].cnt > 0:
            print(f"  {shift_name}: already has {existing[0].cnt} periods, skipping")
            continue

        doc = frappe.get_doc("Shift Type", shift_name)
        for pnum, pname, start, end, is_break in periods:
            doc.append("shift_periods", {
                "period_number": pnum,
                "period_name": pname,
                "start_time": start,
                "end_time": end,
                "is_break": is_break,
            })
        try:
            doc.save(ignore_permissions=True)
            frappe.db.commit()
            print(f"  {shift_name}: added {len(periods)} periods via get_doc")
        except Exception as e:
            frappe.clear_messages()
            print(f"  {shift_name}: ERROR {e}")

    # Verify
    print("\n--- Verification ---")
    for shift_name in SHIFT_DEFS:
        cnt = frappe.db.sql(
            "SELECT COUNT(*) as cnt FROM `tabShift Period` WHERE parent=%s", shift_name, as_dict=True
        )
        print(f"  {shift_name}: {cnt[0].cnt} periods")
