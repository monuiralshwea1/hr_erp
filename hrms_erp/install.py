def after_install():
	"""Run all setup steps (idempotent, isolated)."""
	steps = [
		("Custom Fields", create_custom_fields),
		("Workspaces", create_workspaces),
		("Number Cards", create_number_cards),
		("Dashboard Charts", create_dashboard_charts),
		("Notifications", create_notifications),
		("Translations", create_translations),
		("Workflows", create_workflows),
		("Print Formats", create_print_formats),
	]
	for label, fn in steps:
		try:
			fn()
		except Exception as e:
			import traceback
			print(f"STEP_ERR {label}: {traceback.format_exc()}")
	frappe.db.commit()


def _ensure_custom_field(fields):
	"""Create custom field only if it does not already exist."""
	if frappe.db.exists("Custom Field", {"dt": fields["dt"], "fieldname": fields["fieldname"]}):
		return
	try:
		if frappe.get_meta(fields['dt']).has_field(fields['fieldname']):
			return
	except Exception:
		pass
	try:
		doc = frappe.new_doc("Custom Field")
		doc.dt = fields['dt']
		doc.fieldname = fields['fieldname']
		doc.fieldtype = fields['fieldtype']
		doc.label = fields.get('label', '')
		doc.module = 'hrms-erp'
		if fields.get('options'):
			doc.options = fields['options']
		if fields.get('default') is not None:
			doc.default = fields['default']
		if fields.get('description'):
			doc.description = fields['description']
		if fields.get('insert_after'):
			doc.insert_after = fields['insert_after']
		doc.flags.ignore_permissions = True
		doc.insert()
	except Exception as e:
		pass  # silently skip errors


def create_custom_fields():
	fields = CUSTOM_FIELDS
