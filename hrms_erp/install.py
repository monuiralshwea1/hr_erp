def _clean_ws_data(ws):
	"""Clean workspace data for frappe import."""
	clean = {
		"name": ws["name"],
		"label": ws.get("label", ws["name"]),
		"module": ws.get("module", "hrms-erp"),
		"doctype": "Workspace",
		"public": 1,
	}
	for k in ("icon", "indicator_color", "is_hidden", "content", "title"):
		if k in ws and ws[k] is not None:
			clean[k] = ws[k]
	if "content" in clean and not isinstance(clean["content"], str):
		clean["content"] = json.dumps(clean["content"], ensure_ascii=False)
	# Clean child tables (shortcuts, links, charts)
	for child_key in ("shortcuts", "links", "charts", "number_cards"):
		if child_key in ws and ws[child_key]:
			cleaned_children = []
			for child in ws[child_key]:
				cc = {}
				for ck, cv in child.items():
					if cv is not None and ck not in ("name", "owner", "creation", "modified", "modified_by", "docstatus"):
						cc[ck] = cv
				cc["doctype"] = child.get("doctype", "Workspace Shortcut")
				cc["parent"] = ws["name"]
				cc["parentfield"] = child_key
				cc["parenttype"] = "Workspace"
				cleaned_children.append(cc)
			clean[child_key] = cleaned_children
	return clean


def create_workspaces():
	"""Create workspaces from embedded data."""
	frappe.flags.in_install = "hr_erp"
	created = 0
	for ws in WORKSPACES:
		try:
			if frappe.db.exists('Workspace', ws['name']):
				continue
			ws_doc = frappe.get_doc(_clean_ws_data(ws))
			ws_doc.flags.ignore_permissions = True
			ws_doc.insert()
			frappe.db.commit()
			created += 1
		except Exception as e:
			print(f"  WARN workspace '{ws.get('name', '?')}': {str(e)[:200]}")
	frappe.flags.in_install = None
	frappe.db.commit()
	print(f"Workspaces: {created} created, {len(WORKSPACES)} total")


