def create_notifications():
	for nf in NOTIFICATIONS:
		try:
			if frappe.db.exists('Notification', nf['name']):
				continue
			doc = frappe.new_doc('Notification')
			for k, v in nf.items():
				if v is not None and v != '':
					doc.set(k, v)
			doc.flags.ignore_permissions = True
			doc.insert()
		except Exception:
			pass
	print(f"Notifications: {len(NOTIFICATIONS)} defined")


