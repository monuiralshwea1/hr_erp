def create_translations():
	count = 0
	for t in TRANSLATIONS:
		try:
			if not t.get('source_text') or not t.get('translated_text'):
				continue
			existing = frappe.db.exists('Translation', {
				'language': t['language'],
				'source_text': t['source_text'],
			})
			if existing:
				continue
			doc = frappe.new_doc('Translation')
			doc.language = t['language']
			doc.source_text = t['source_text']
			doc.translated_text = t['translated_text']
			if t.get('context'):
				doc.context = t['context']
			doc.flags.ignore_permissions = True
			doc.insert()
			count += 1
		except Exception:
			pass
	print(f"Translations: {count} created")


