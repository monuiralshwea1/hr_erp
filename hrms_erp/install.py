def create_number_cards():
	for nc in NUMBER_CARDS:
		try:
			if frappe.db.exists('Number Card', nc['name']):
				continue
			doc = frappe.new_doc('Number Card')
			for k, v in nc.items():
				doc.set(k, v)
			doc.flags.ignore_permissions = True
			doc.insert()
		except Exception:
			pass
	print(f"Number Cards: {len(NUMBER_CARDS)} defined")


