def create_workflows():
	for wf in WORKFLOWS:
		try:
			wf_name = wf.get('name', wf.get('document_type', ''))
			if frappe.db.exists('Workflow', wf_name):
				continue
			doc = frappe.new_doc('Workflow')
			doc.workflow_name = wf_name
			doc.document_type = wf['document_type']
			doc.workflow_state_field = wf.get('workflow_state_field', 'workflow_state')
			doc.is_active = wf.get('is_active', 1)
			doc.override_status = wf.get('override_status', 0)
			doc.send_email_alert = wf.get('send_email_alert', 0)
			doc.flags.ignore_permissions = True
			doc.insert()
		except Exception:
			pass
	print(f"Workflows: {len(WORKFLOWS)} defined")


